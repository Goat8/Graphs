K = 8
B = K + 1

phi_minus = 1
phi_zero = B
phi_plus = B**2

for a in range(K + 1):
    for b in range(K + 1 - a):
        for c in range(K + 1 - a - b):

            if a + b + c == 0:
                continue

            total = (
                a * phi_minus +
                b * phi_zero +
                c * phi_plus
            )

            decoded_a = total % B
            decoded_b = (total // B) % B
            decoded_c = total // (B**2)

            assert (a, b, c) == (
                decoded_a, decoded_b, decoded_c
            )

print("all 164 triples have been decoded correctly")